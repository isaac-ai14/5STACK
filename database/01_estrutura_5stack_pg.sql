CREATE TABLE rank (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_patente VARCHAR(50) NOT NULL,
    divisao INT,
    tier_nivel INT NOT NULL UNIQUE,
    icone_url VARCHAR(255)
);

CREATE TABLE funcao (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_funcao VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    puuid VARCHAR(78) UNIQUE,
    game_name VARCHAR(50),
    tag_line VARCHAR(10),
    email VARCHAR(100) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    rank_id INT REFERENCES rank(id),
    rr_atual INT,
    reputacao_media NUMERIC(3,2) DEFAULT NULL,
    atualizado_em TIMESTAMP,
    CONSTRAINT chk_usuario_rr CHECK (rr_atual >= 0),
    CONSTRAINT chk_usuario_reputacao CHECK (reputacao_media BETWEEN 1 AND 5)
);

CREATE TABLE usuario_funcao (
    usuario_id INT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    funcao_id INT NOT NULL REFERENCES funcao(id),
    eh_principal BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (usuario_id, funcao_id)
);

CREATE TABLE lobby (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lider_id INT NOT NULL REFERENCES usuario(id),
    titulo VARCHAR(100) NOT NULL,
    vagas_totais INT NOT NULL DEFAULT 5,
    rank_min_id INT REFERENCES rank(id),
    rank_max_id INT REFERENCES rank(id),
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_lobby_vagas CHECK (vagas_totais BETWEEN 1 AND 5),
    CONSTRAINT chk_lobby_status CHECK (status IN ('ABERTO', 'PROCURANDO', 'FECHADO'))
);

CREATE TABLE lobby_membro (
    lobby_id INT NOT NULL REFERENCES lobby(id) ON DELETE CASCADE,
    usuario_id INT NOT NULL REFERENCES usuario(id),
    entrou_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (lobby_id, usuario_id)
);

CREATE TABLE convite (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lobby_id INT NOT NULL REFERENCES lobby(id) ON DELETE CASCADE,
    remetente_id INT NOT NULL REFERENCES usuario(id),
    destinatario_id INT NOT NULL REFERENCES usuario(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_convite_status CHECK (status IN ('PENDENTE', 'ACEITO', 'RECUSADO', 'CANCELADO')),
    CONSTRAINT chk_convite_usuarios CHECK (remetente_id <> destinatario_id)
);

